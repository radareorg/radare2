#!/usr/bin/env python3
"""Generate HFS+ Unicode 3.2 decomposition and fixed filename-equivalence data."""
import argparse
import hashlib
from pathlib import Path
import re
import unicodedata
import urllib.request

URL = 'https://raw.githubusercontent.com/apple-oss-distributions/hfs/main/core/UCStringCompareData.h'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--folding-table', type=Path, help='local TN1150 case-equivalence table, for offline regeneration')
    args = parser.parse_args()
    data = args.folding_table.read_bytes() if args.folding_table else urllib.request.urlopen(URL).read()
    expected = '88773669ce79ebe2d6bcc84d3341c3c2586e649984ac97453adb1b8706440464'
    if hashlib.sha256(data).hexdigest() != expected:
        raise SystemExit('Unexpected HFS+ equivalence data; inspect the specification before updating')
    source = data.decode().split('gLowerCaseTable[]')[1].split('{', 1)[1].split('}', 1)[0]
    source = re.sub(r'/\*.*?\*/', '', source, flags=re.S)
    values = [int(value, 16) for value in re.findall(r'0x([0-9a-fA-F]+)', source)]
    latin = data.decode().split('gLatinCaseFold[]')[1].split('{', 1)[1].split('}', 1)[0]
    latin = re.sub(r'/\*.*?\*/', '', latin, flags=re.S)
    latin = [int(value, 16) for value in re.findall(r'0x([0-9a-fA-F]+)', latin)]
    assert len(latin) == 256
    folds = [(ch, latin[ch] if ch < 256 else values[values[ch >> 8] + (ch & 255)] if values[ch >> 8] else ch) for ch in range(65536)]
    folds = [(ch, value) for ch, value in folds if ch != value]
    ucd = unicodedata.ucd_3_2_0

    def decompose(ch):
        if 0x2000 <= ch <= 0x2fff or 0xf900 <= ch <= 0xfaff or 0x2f800 <= ch <= 0x2faff:
            return [ch]
        value = ucd.decomposition(chr(ch))
        if not value or value.startswith('<'):
            return [ch]
        return [item for value_ in value.split() for item in decompose(int(value_, 16))]

    offsets, decomposed, combining = [], [], []
    for ch in range(0x110000):
        value = decompose(ch)
        if value != [ch]:
            assert len(value) < 8
            offsets.append((ch, (len(decomposed) << 3) | len(value)))
            decomposed.extend(value)
        category = ucd.combining(chr(ch))
        if category:
            combining.append((ch, category))
    output = ['/* radare - LGPL - Copyright 2026 - pancake */', '',
              '// Generated by sys/hfs-unicode.py from Unicode 3.2 and TN1150 equivalence facts.',
              '// HFS+ comparison reference: ' + URL, '',
              'typedef struct { ut32 code, value; } HfsUnicode;', '']
    for name, entries in (('hfs_fold', folds), ('hfs_decomposition', offsets), ('hfs_combining', combining)):
        output.append(f'static const HfsUnicode {name}[] = {{')
        for start in range(0, len(entries), 6):
            output.append('\t' + ', '.join('{ 0x%x, 0x%x }' % entry for entry in entries[start:start + 6]) + ',')
        output.extend(['};', ''])
    output.append('static const ut32 hfs_decomposed[] = {')
    for start in range(0, len(decomposed), 12):
        output.append('\t' + ', '.join('0x%x' % value for value in decomposed[start:start + 12]) + ',')
    output.extend(['};', ''])
    destination = Path(__file__).resolve().parents[1] / 'libr/fs/p/fs_hfsplus_unicode.inc.c'
    destination.write_text('\n'.join(output))


if __name__ == '__main__':
    main()
